const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
let code=fs.readFileSync('app.js','utf8').replace(/init\(\);\s*$/,'');
const snapshot=JSON.parse(fs.readFileSync('data/app.json','utf8'));
const ctx={document:{getElementById:()=>null},window:{matchMedia:()=>({matches:false})},innerWidth:1280,innerHeight:720,console,URL,Intl,Date,Map,Set,setTimeout,clearTimeout};
vm.createContext(ctx);
vm.runInContext(code+'\ndata=JSON.parse('+JSON.stringify(JSON.stringify(snapshot))+');',ctx);
function run(s){return vm.runInContext(s,ctx);}
assert.equal(run('filteredEvents().length'),120);
assert.equal(run('currentSites().length'),92);
assert.equal(run('visibleBrands(filteredEvents()).length'),5);
assert.equal(run('state.status="uncertain"; filteredEvents().length'),11);
assert.equal(run('state.status="future_announced"; filteredEvents().length'),9);
assert.equal(run('state.status="all";state.month="1";monthState({start_date:"2025-12-05",end_date:"2026-01-05"})'),'match');
assert.equal(run('monthState({start_date:"",end_date:"2026-01-05"})'),'unknown');
assert.equal(run('monthState({start_date:"2026-02-01",end_date:"2026-02-05"})'),'outside');
assert.equal(run('monthState({start_date:"2026-01-20",end_date:"2026-01-10"})'),'unknown');
assert.equal(run('state.area="NONEXISTENT";filteredEvents().length'),0);
assert.equal(run('visibleBrands(filteredEvents()).length'),0);
assert.equal(run('esc("<script>&\\\"")'),'&lt;script&gt;&amp;&quot;');
assert.equal(run('safeUrl("javascript:alert(1)")'),null);
assert.ok(run('safeUrl("https://example.com")').startsWith('https://'));
run('state.area="all";state.month="all";state.status="all";state.tab="distribution";');
assert.ok(run('highlightedBuildingIds(currentSites()).size')>0);
const selected=snapshot.sites.find(s=>s.metrics?.nearby_50m_building_ids.length>0);
run('state.tab="oda";state.selected='+JSON.stringify(selected.site_id));
assert.deepEqual([...run('highlightedBuildingIds(currentSites())')].sort(),[...selected.metrics.nearby_50m_building_ids].sort());
run('state.selected=null;');
assert.ok(run('highlightedBuildingIds(currentSites()).size')>=selected.metrics.nearby_50m_building_ids.length);
const html=fs.readFileSync('index.html','utf8');
assert.ok(html.indexOf('id="filters"')<html.indexOf('<nav class="tabs"'));
assert.ok(html.includes('type="range"')&&html.includes('id="allYear"'));
assert.ok(!code.includes('siteSearch')&&!code.includes('renderScatter')&&!code.includes('Unverified ODA source lead'));
assert.ok(!html.includes('TEMPORARY<br>GROUNDS'));
assert.ok(html.includes('mapbox-gl-js/v3.33.0')&&!html.includes('leaflet'));
run('var flight;map={getBearing:()=>15,flyTo:options=>{flight=options}};focus3D({longitude:103.82,latitude:1.35});');
assert.equal(run('flight.pitch'),60);assert.equal(run('flight.zoom'),17.2);assert.equal(run('flight.bearing'),55);
assert.deepEqual([...run('flight.center')],[103.82,1.35]);
run('reduced.matches=true;focus3D({longitude:103.82,latitude:1.35});');assert.equal(run('flight.duration'),0);
run('reduced.matches=false;map={fitBounds:(bounds,options)=>{flight=options}};overview();');
assert.equal(run('flight.pitch'),0);assert.equal(run('flight.bearing'),0);
assert.equal(run('markerGroups([{longitude:103.8,latitude:1.3},{longitude:103.8,latitude:1.3},{longitude:null,latitude:null}]).length'),1);
console.log('PASS: snapshot counts, uncertainty, future filters, cross-year month overlap, missing/reversed dates, empty brand filters, HTML escaping and URL allowlist.');
